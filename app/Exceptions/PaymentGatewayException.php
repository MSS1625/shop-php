<?php

namespace App\Exceptions;

use RuntimeException;

/**
 * خطای عمومی درگاه پرداخت (خطای پذیرنده، شبکه یا درگاه)
 */
class PaymentGatewayException extends RuntimeException
{
    /** پیام‌های فارسی خطاهای شناخته‌شده API نسخه ۴ زرین‌پال */
    public const ZARINPAL_MESSAGES = [
        -9 => 'اطلاعات ارسالی به درگاه معتبر نیست (خطای اعتبارسنجی).',
        -10 => 'این شناسه پذیرنده فعال نیست؛ با پشتیبانی زرین‌پال تماس بگیرید.',
        -11 => 'شناسه پذیرنده (Merchant ID) یافت نشد.',
        -12 => 'تلاش بیش از حد؛ لطفا چند دقیقه بعد دوباره امتحان کنید.',
        -15 => 'مبلغ تراکنش بیش از سقف مجاز پذیرنده است.',
        -16 => 'سطح پذیرندگی حساب شما برای این پرداخت کافی نیست.',
        -30 => 'امکان پرداخت مجدد برای این تراکنش وجود ندارد.',
        -31 => 'حساب بانکی پذیرنده برای این تراکنش در دسترس نیست.',
        -33 => 'مبلغ تراکنش با مبلغ پرداخت‌شده تطابق ندارد.',
        -34 => 'خطای تقسیم مبلغ تراکنش (شبه‌کارمزد).',
        -40 => 'اطلاعات احراز تراکنش نامعتبر است.',
        -50 => 'اطلاعات ارسالی با اطلاعات پرداخت یکسان نیست.',
        -51 => 'پرداخت ناموفق بود.',
        -52 => 'خطای غیرمنتظره در پرداخت؛ لطفا دوباره تلاش کنید.',
        -53 => 'این تراکنش متعلق به این پذیرنده نیست.',
        -54 => 'شناسه ارجاع (Authority) نامعتبر است.',
        201 => 'تراکنش تایید نشد؛ پرداخت ناموفق است.',
    ];

    /**
     * ساخت اکسپشن با پیام فارسی بر اساس کد خطای زرین‌پال
     */
    public static function fromZarinpalCode(?int $code, array $errors = []): static
    {
        $message = self::ZARINPAL_MESSAGES[$code] ?? 'خطای ناشناخته درگاه پرداخت.';

        // اگر درگاه جزئیات بیشتری فرستاده باشد، اولین پیام آن هم ضمیمه می‌شود
        $detail = collect($errors)->pluck('message')->filter()->first();
        if ($detail && $code !== null && ! isset(self::ZARINPAL_MESSAGES[$code])) {
            $message .= ' ('.$detail.')';
        }

        return new static($message, $code ?? 0);
    }
}
